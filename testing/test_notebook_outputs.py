"""Execute ``notebook_output_checks.ipynb`` and verify each cell's outputs.

The notebook (generated by ``make_notebook_output_checks.py``) collects
every situation in which Jupyter could show ramantools output twice, show
something it should not (a ``None`` echo, a second copy of a figure) or
drop something it should show (status text lost between ``print`` and
``logging``). A human can review the executed notebook by eye; this
module does the same comparison mechanically.

How it works:

* the notebook is executed once per test session with ``nbclient``
  (``allow_errors=True`` so that every cell runs and all failures are
  reported together, not only the first);
* each code cell's ``metadata['expect']`` dict states what the cell may
  emit; see the module docstring of ``make_notebook_output_checks.py``
  for the keys;
* one parametrised test per code cell compares the real outputs with
  the expectation. A separate test asserts that no cell raised.

The executed notebook is written to the pytest temporary directory and its
path is included in every failure message so the offending cell can be
opened in Jupyter.

Skipped automatically when ``nbformat`` / ``nbclient`` are not installed.
"""

import subprocess  # run the generator for the sync check
import sys  # repo root on sys.path for the kernel-less parts
from pathlib import Path  # path handling

import pytest

# Both packages ship with Jupyter; skip cleanly on a minimal install.
nbformat = pytest.importorskip('nbformat')
nbclient = pytest.importorskip('nbclient')

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

NOTEBOOK = Path(__file__).resolve().parent / 'notebook_output_checks.ipynb'
GENERATOR = Path(__file__).resolve().parent / 'make_notebook_output_checks.py'

# Read the notebook once at import time so the code cells can be used as
# pytest parameters (ids are the first source line of each cell).
_SOURCE_NB = nbformat.read(NOTEBOOK, as_version=4)
_CODE_CELL_INDICES = [i for i, c in enumerate(_SOURCE_NB.cells) if c.cell_type == 'code']


def _cell_id(index: int) -> str:
        """Readable pytest id: cell number plus its first non-comment line."""
        source = _SOURCE_NB.cells[index].source
        first = next((ln for ln in source.splitlines() if ln.strip() and not ln.lstrip().startswith('#')), '')
        return f'cell{index:02d}:{first.strip()[:50]}'


@pytest.fixture(scope='module')
def executed(tmp_path_factory):
        """Run the notebook once; return ``(notebook_node, path_of_executed_copy)``.

        The kernel's working directory is the repository root so the setup
        cell finds ``testing/synthetic.py`` and the optional ``.wip`` section
        finds ``test-data/`` exactly as an interactive session would.
        """
        nb = nbformat.read(NOTEBOOK, as_version=4)
        client = nbclient.NotebookClient(
                nb,
                timeout=600,  # the map peakfit cells take a few seconds each
                kernel_name='python3',
                allow_errors=True,  # keep going so every cell is reported
                resources={'metadata': {'path': str(ROOT)}},
        )
        client.execute()
        out = tmp_path_factory.mktemp('notebook') / 'notebook_output_checks.executed.ipynb'
        nbformat.write(nb, out)
        return nb, out


# ---------------------------------------------------------------------------
# Output inspection helpers
# ---------------------------------------------------------------------------

def _stream_text(cell, name: str) -> str:
        """Concatenate all ``stream`` outputs of ``cell`` written to ``name``."""
        return ''.join(o.get('text', '') for o in cell.outputs if o.output_type == 'stream' and o.get('name') == name)


def _image_count(cell) -> int:
        """Number of outputs (display_data or execute_result) carrying a PNG."""
        return sum(1 for o in cell.outputs if o.output_type in ('display_data', 'execute_result') and 'image/png' in o.get('data', {}))


def _results(cell) -> list:
        """All ``execute_result`` outputs of the cell (normally zero or one)."""
        return [o for o in cell.outputs if o.output_type == 'execute_result']


def _result_text(cell) -> str:
        """text/plain of the echo(es), used for the includes / excludes checks."""
        return ''.join(o.get('data', {}).get('text/plain', '') for o in _results(cell))


def _errors(cell) -> list:
        """``error`` outputs (an exception escaped the cell)."""
        return [o for o in cell.outputs if o.output_type == 'error']


def _check(cell, expect: dict, where: str) -> list:
        """Compare one cell's outputs with its expectation; return failure strings.

        Every rule is evaluated so a failing cell reports all of its
        problems at once. ``where`` is prepended to each message so the
        caller can point at the executed notebook on disk.
        """
        problems = []
        # Optional sections (the .wip cells) are silent when their input is
        # missing; a cell with no output at all is then treated as skipped.
        if expect.get('when_has_output') and not cell.outputs:
                return problems
        if _errors(cell):
                tb = '\n'.join(_errors(cell)[0].get('traceback', []))
                problems.append(f'{where}: cell raised\n{tb}')
        if 'images' in expect:
                n = _image_count(cell)
                if n != expect['images']:
                        problems.append(f'{where}: expected {expect["images"]} image(s), got {n}')
        # More than one execute_result is impossible for a single cell in
        # practice, but the check is cheap and documents the intent.
        if 'result' in expect:
                has = bool(_results(cell))
                if has != expect['result']:
                        kind = 'an echo (execute_result)' if has else 'no echo'
                        problems.append(f'{where}: expected result={expect["result"]}, cell produced {kind}: {_result_text(cell)[:120]!r}')
        for stream in ('stdout', 'stderr'):
                text = _stream_text(cell, stream)
                if stream in expect and bool(text) != expect[stream]:
                        problems.append(f'{where}: expected {stream}={expect[stream]}, got {text[:200]!r}')
                once = expect.get(f'{stream}_once')
                if once is not None:
                        count = text.count(once)
                        if count != 1:
                                problems.append(f'{where}: {once!r} should appear once on {stream}, found {count} times in {text[:300]!r}')
        if 'result_includes' in expect and expect['result_includes'] not in _result_text(cell):
                problems.append(f'{where}: echo should contain {expect["result_includes"]!r}, got {_result_text(cell)[:200]!r}')
        if 'result_excludes' in expect and expect['result_excludes'] in _result_text(cell):
                problems.append(f'{where}: echo must not contain {expect["result_excludes"]!r}')
        return problems


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------

def test_every_code_cell_has_an_expectation():
        """Guard against adding a cell to the generator without a contract.

        A cell without ``expect`` metadata would execute but never be
        checked, which silently weakens the notebook as a regression test.
        """
        missing = [_cell_id(i) for i in _CODE_CELL_INDICES if 'expect' not in _SOURCE_NB.cells[i].metadata]
        assert not missing, f'code cells without expect metadata: {missing}'


def test_notebook_matches_generator(tmp_path):
        """The committed notebook must be what the generator produces.

        The generator is the source of truth; editing it without
        regenerating (or hand-editing the .ipynb) would let the two drift
        apart. Only sources and metadata are compared, never outputs.
        """
        target = tmp_path / 'regenerated.ipynb'
        subprocess.run([sys.executable, str(GENERATOR), str(target)], check=True, capture_output=True)
        fresh = nbformat.read(target, as_version=4)

        def essence(nb):
                # Cell ids are random per nbformat write; strip them before comparing.
                return [(c.cell_type, c.source, {k: v for k, v in c.metadata.items()}) for c in nb.cells]

        assert essence(fresh) == essence(_SOURCE_NB), (
                'notebook_output_checks.ipynb is out of date: run python testing/make_notebook_output_checks.py'
        )


def test_notebook_runs_without_errors(executed):
        """No cell may raise; the in-cell asserts are part of the contract."""
        nb, path = executed
        failed = []
        for i in _CODE_CELL_INDICES:
                cell = nb.cells[i]
                for err in _errors(cell):
                        failed.append(f'{_cell_id(i)}: {err.get("ename")}: {err.get("evalue")}')
        assert not failed, f'cells raised (see {path}):\n' + '\n'.join(failed)


@pytest.mark.parametrize('index', _CODE_CELL_INDICES, ids=_cell_id)
def test_cell_outputs_match_expectation(executed, index):
        """Per-cell check of images / echo / stdout / stderr against ``expect``."""
        nb, path = executed
        cell = nb.cells[index]
        expect = cell.metadata.get('expect', {})
        problems = _check(cell, expect, _cell_id(index))
        assert not problems, f'(executed notebook: {path})\n' + '\n'.join(problems)
